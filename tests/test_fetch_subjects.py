MARC = "http://www.loc.gov/MARC21/slim"


def marc_record(body: str) -> str:
    return f'<record xmlns="{MARC}" type="Bibliographic">{body}</record>'


def sru_response(records: list[str], total: int | None = None) -> str:
    wrapped = "".join(
        "<record><recordSchema>MARC21-xml</recordSchema><recordPacking>xml</recordPacking>"
        f"<recordData>{record}</recordData></record>" for record in records
    )
    count = len(records) if total is None else total
    return ('<?xml version="1.0" encoding="UTF-8"?>'
            '<searchRetrieveResponse xmlns="http://www.loc.gov/zing/srw/"><version>1.1</version>'
            f"<numberOfRecords>{count}</numberOfRecords><records>{wrapped}</records>"
            "</searchRetrieveResponse>")


def sub(code: str, value: str) -> str:
    return f'<subfield code="{code}">{value}</subfield>'


def field(tag: str, *subfields: str, ind1: str = " ", ind2: str = " ") -> str:
    return f'<datafield tag="{tag}" ind1="{ind1}" ind2="{ind2}">{"".join(subfields)}</datafield>'


def gnd0(identifier: str) -> str:
    return (sub("0", f"(DE-588){identifier}") + sub("0", f"https://d-nb.info/gnd/{identifier}")
            + sub("0", "(DE-101)040277437"))


