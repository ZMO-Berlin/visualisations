def record(catalogue: str, record_id: str, isbns, subjects=(), title: str = "", ddc=()) -> CatalogueRecord:
    return CatalogueRecord(
        catalogue=catalogue, id=record_id, isbns=frozenset(isbns), title=title,
        words=fs.title_words(title), subjects=tuple(subjects), ddc=tuple(ddc),
    )


def raw_book(slug: str, isbn: str, title: str = "Muslim Worlds", document_type: str = "Monographs") -> dict:
    return {"slug": slug, "title": title, "isbn": isbn, "document_type": document_type}


class IsbnTests(unittest.TestCase):
    def test_check_digits_and_conversion(self) -> None:
        self.assertEqual(to_isbn13("3593397609"), "9783593397603")
        self.assertEqual(to_isbn13("178238779X"), "9781782387794")
        self.assertEqual(to_isbn13("178238779x"), "9781782387794")
        self.assertEqual(to_isbn13("978-3-11-068496-4"), "9783110684964")
        self.assertEqual(to_isbn10("9783593397603"), "3593397609")
        self.assertEqual(to_isbn10("9781782387794"), "178238779X")
        self.assertIsNone(to_isbn10("9791032300000"))  # 979 has no ISBN-10
        self.assertIsNone(to_isbn13("3593397608"))  # wrong check digit
        self.assertIsNone(to_isbn13("9783593397604"))

    def test_messy_register_values(self) -> None:
        cases = {
            "978-977-821-491-8": (["9789778214918"], []),
            "9783111696492 / 9783111697215": (["9783111696492", "9783111697215"], []),
            "9783112225172; 9783112225165": (["9783112225172", "9783112225165"], []),
            "Print-ISBN: 978-3-8376-8312-7; PDF-ISBN: 978-3-8394-7918-6":
                (["9783837683127", "9783839479186"], []),
            "ISBN 9780367503901": (["9780367503901"], []),
            "ISBN 978-3-11-078035-2": (["9783110780352"], []),
            "3-87997-626-0": (["9783879976263"], []),
            "978 3 8376 8312 7": (["9783837683127"], []),
            # The same book twice, separated by a space only.
            "3593397609 9783593397603": (["9783593397603"], []),
            # Truncated, too long, or a bad check digit: counted, not queried.
            "978110847879": ([], ["978110847879"]),
            "97801994817433": ([], ["97801994817433"]),
            "3-87997-626-2": ([], ["3879976262"]),
            "3-86093-144-9": ([], ["3860931449"]),  # the check digit is X
            # A URL is not an ISBN, and its digit runs are not candidates.
            "https://www.cambridge.org/core/journals/africa/volume/83C9CC0A413A3511CA4319782F0A07DB?pageNum=1":
                ([], []),
        }
        for value, expected in cases.items():
            with self.subTest(value=value):
                self.assertEqual(parse_isbns(value), expected)

    def test_split_keeps_order_and_ignores_short_runs(self) -> None:
        self.assertEqual(split_isbn_field("3-86093-144-X (2004), 314 p."), ["386093144X"])
        self.assertEqual(split_isbn_field(None), [])

    def test_query_forms_carry_both_lengths(self) -> None:
        self.assertEqual(query_forms(["9783593397603", "9791032300000"]),
                         ["9783593397603", "3593397609", "9791032300000"])

    def test_book_preparation(self) -> None:
        book = prepare_book(raw_book("b", "978110847879 / 3593397609"))
        self.assertEqual(book.isbns, ("9783593397603",))
        self.assertEqual(book.invalid, ("978110847879",))
        self.assertEqual(book.fp, fingerprint(["9783593397603"]))
        # The fingerprint follows the normalised ISBNs, not how they were typed.
        self.assertEqual(prepare_book(raw_book("b", "978-3-593-39760-3")).fp, book.fp)

    def test_scope(self) -> None:
        self.assertTrue(fs.in_scope(raw_book("a", "3593397609")))
        self.assertTrue(fs.in_scope(raw_book("a", "3593397609", document_type="Edited volumes")))
        self.assertFalse(fs.in_scope(raw_book("a", "3593397609",
                                              document_type="Contributions to an edited volume")))
        self.assertFalse(fs.in_scope(raw_book("a", "  ")))


class LobidParsingTests(unittest.TestCase):
    def test_chain_components_and_single_subjects(self) -> None:
        parsed = parse_lobid_record(LOBID_MEMBER)
        self.assertEqual(parsed.catalogue, "lobid")
        self.assertEqual(parsed.id, "https://lobid.org/resources/990191745220206441")
        # The related edition's ISBN is not the record's own.
        self.assertEqual(parsed.isbns, frozenset({"9783593397603"}))
        self.assertEqual(parsed.subjects, (
            Heading("4003860-9", "Außereuropäische Länder", "PlaceOrGeographicName"),
            Heading("4557997-0", "Globalisierung", "SubjectHeading"),
            Heading("118586408", "Nehru, Jawaharlal", "Person"),
        ))
        self.assertEqual(parsed.ddc, ("909.825",))
        self.assertIn("globalisierung", parsed.words)

    def test_class_folding(self) -> None:
        self.assertEqual(gnd_class(["DifferentiatedPerson"]), "Person")
        self.assertEqual(gnd_class(["CorporateBody", "TerritorialCorporateBodyOrAdministrativeUnit"]),
                         "PlaceOrGeographicName")
        self.assertEqual(gnd_class(["SeriesOfConferenceOrEvent"]), "ConferenceOrEvent")
        self.assertEqual(gnd_class(["Family"]), "Family")
        self.assertEqual(gnd_class(["Work", "Expression"]), "Work")
        self.assertEqual(gnd_class(["EthnographicName"]), "SubjectHeading")
        self.assertEqual(gnd_class(["SomethingNew"]), "SubjectHeading")
        self.assertEqual(gnd_class(None), "SubjectHeading")

    def test_response_shape(self) -> None:
        members, total = parse_lobid_response(json.dumps({"totalItems": 1, "member": [LOBID_MEMBER]}))
        self.assertEqual((len(members), total), (1, 1))
        with self.assertRaises(SubjectsError):
            parse_lobid_response("<html>maintenance</html>")
        with self.assertRaises(SubjectsError):
            parse_lobid_response(json.dumps({"error": "bad query"}))

    def test_query_syntax(self) -> None:
        self.assertEqual(fs.lobid_query(["9783593397603"]), "isbn:9783593397603")
        self.assertEqual(fs.lobid_query(["9783593397603", "3593397609"]),
                         "isbn:(9783593397603 OR 3593397609)")
        self.assertEqual(fs.dnb_query(["9783593397603", "3593397609"]),
                         "num=9783593397603 or num=3593397609")


class DnbParsingTests(unittest.TestCase):
    def parsed(self) -> CatalogueRecord:
        return parse_dnb_record(ET.fromstring(DNB_RECORD))

    def test_identity_isbns_and_title(self) -> None:
        parsed = self.parsed()
        self.assertEqual(parsed.id, "https://d-nb.info/1238695175")
        # 020 $a/$9 only: neither a cancelled ISBN ($z) nor the other edition (776).
        self.assertEqual(parsed.isbns, frozenset({"9783110726534"}))
        self.assertEqual(parsed.title, "The Muslim Worlds : Religion and Society")

    def test_chains_first_then_other_fields_without_machine_headings(self) -> None:
        parsed = self.parsed()
        self.assertEqual([(h.id, h.label, h.type) for h in parsed.subjects], [
            ("4073172-8", "Islamische Staaten", "PlaceOrGeographicName"),
            ("4354651-1", "Religiöse Identität", "SubjectHeading"),
            ("4027743-4", "Islam", "SubjectHeading"),
            ("118708546", "Ibn-Taimīya, Aḥmad Ibn-ʿAbd-al-Ḥalīm", "Person"),
            ("4027743-4", "Islam", "SubjectHeading"),
            ("4049396-9", "Religion", "SubjectHeading"),
            ("4073172-8", "Islamische Staaten", "PlaceOrGeographicName"),
            ("4244159-6", "Indien (Südost)", "PlaceOrGeographicName"),
        ])
        # Labels are NFC even though the DNB decomposes accents.
        self.assertEqual(parsed.subjects[1].label, "Religiöse Identität")
        # "Muslim" and "Gesellschaftsordnung" (883 indicator 1) and the machine
        # DDC number (indicator 0) are dropped; the genre term is not a subject.
        labels = {h.label for h in parsed.subjects}
        self.assertNotIn("Muslim", labels)
        self.assertNotIn("Gesellschaftsordnung", labels)
        self.assertNotIn("Konferenzschrift", labels)
        self.assertEqual(parsed.machine, 3)
        self.assertEqual(parsed.ddc, ("297.09051",))

    def test_response_and_diagnostics(self) -> None:
        records, total = parse_dnb_response(sru_response([DNB_RECORD]))
        self.assertEqual((len(records), total), (1, 1))
        diagnostic = ('<searchRetrieveResponse xmlns="http://www.loc.gov/zing/srw/">'
                      '<version>1.1</version><numberOfRecords>0</numberOfRecords>'
                      '<diagnostics><diagnostic xmlns="http://www.loc.gov/zing/srw/diagnostic/">'
                      '<uri>info:srw/diagnostic/1/10</uri><message>Query syntax error</message>'
                      '</diagnostic></diagnostics></searchRetrieveResponse>')
        with self.assertRaisesRegex(SubjectsError, "Query syntax error"):
            parse_dnb_response(diagnostic)
        with self.assertRaises(SubjectsError):
            parse_dnb_response("not xml")


class MatchingTests(unittest.TestCase):
    def test_record_without_the_queried_isbn_is_refused(self) -> None:
        book = prepare_book(raw_book("b", "9783110726534", title="Claiming and Making Muslim Worlds"))
        own = record("lobid", "https://lobid.org/resources/1", {"9783110726534"},
                     title="Claiming and making Muslim worlds")
        # A DNB record found because its record number equals the ISBN-10.
        other = record("dnb", "https://d-nb.info/311072653X", set(), title="Crossing Muddy Waters")
        related = record("lobid", "https://lobid.org/resources/2", {"9783110727111"},
                         title="Claiming and making Muslim worlds")
        verdict = accept(book, [own, other, related])
        self.assertEqual(verdict.accepted, [own])
        self.assertEqual(verdict.other_isbn, 2)
        self.assertEqual(verdict.other_title, [])

    def test_wrong_isbn_in_the_register_is_refused_by_title(self) -> None:
        book = prepare_book(raw_book(
            "z", "3879976910",
            title="Zukunftsperspektiven der Entwicklungszusammenarbeit als erweiterte "
                  "Kooperations- und Sicherheitspolitik"))
        wrong = record("lobid", "https://lobid.org/resources/3", {"9783879976911"},
                       title="Talḫīs al-adilla li-qawāʿid at-tauḥīd, 2")
        verdict = accept(book, [wrong])
        self.assertEqual(verdict.accepted, [])
        self.assertEqual(verdict.other_title, [wrong])

    def test_title_guard_judges_the_isbn_not_each_record(self) -> None:
        book = prepare_book(raw_book("h", "3110255146", title="Handbuch des Antisemitismus"))
        volume = record("dnb", "https://d-nb.info/1108631630", {"9783110255140"},
                        title="Ereignisse, Dekrete, Kontroversen")
        named = record("lobid", "https://lobid.org/resources/4", {"9783110255140"},
                       title="Handbuch des Antisemitismus, 4: Ereignisse, Dekrete, Kontroversen")
        self.assertEqual(accept(book, [volume, named]).accepted, [volume, named])

    def test_other_scripts_and_transliterations_pass_the_guard(self) -> None:
        arabic = prepare_book(raw_book("a", "9789778214918", title="هوامش مشتركة"))
        self.assertEqual(arabic.words, frozenset())
        transliterated = record("lobid", "x", {"9789778214918"}, title="Hawāmiš muštaraka")
        self.assertEqual(len(accept(arabic, [transliterated]).accepted), 1)
        self.assertEqual(fs.title_words("Die Straße der Moderne"), frozenset({"strasse", "moderne"}))
        turkish = prepare_book(raw_book("t", "9789004175426",
                                        title="Ta'addüd-i zevcat zeyl (Continuation of the Debate)"))
        catalogue = record("dnb", "z", {"9789004175426"}, title="Taʾaddüd-i zevcāt ẕeyl")
        self.assertEqual(len(accept(turkish, [catalogue]).accepted), 1)

    def test_merge_deduplicates_by_gnd_id_dnb_first_with_lobid_labels(self) -> None:
        book = prepare_book(raw_book("m", "9783110726534"))
        dnb = record("dnb", "https://d-nb.info/2", {"9783110726534"}, subjects=[
            Heading("4027743-4", "Islam", "SubjectHeading"),
            Heading("4244159-6", "Indien (Südost)", "PlaceOrGeographicName"),
            Heading("123493390", "Qaraḍāwī, Yūsuf", "Person"),
        ], ddc=["297.09051"])
        lobid_b = record("lobid", "https://lobid.org/resources/b", {"9783110726534"}, subjects=[
            Heading("4040921-1", "Muslim", "SubjectHeading"),
            Heading("4027743-4", "Islam", "SubjectHeading"),
        ], ddc=["297.09"])
        lobid_a = record("lobid", "https://lobid.org/resources/a", {"9783110726534"}, subjects=[
            Heading("123493390", "Qaraḍāwī, Yūsuf al-", "Person"),
            Heading("4020588-5", "Gesellschaft", "SubjectHeading"),
        ], ddc=["297.09051"])
        entry = merge(book, [lobid_b, dnb, lobid_a, lobid_b])
        self.assertEqual(entry["records"], [
            {"catalogue": "dnb", "id": "https://d-nb.info/2"},
            {"catalogue": "lobid", "id": "https://lobid.org/resources/a"},
            {"catalogue": "lobid", "id": "https://lobid.org/resources/b"},
        ])
        self.assertEqual([s["id"] for s in entry["subjects"]],
                         ["4027743-4", "4244159-6", "123493390", "4020588-5", "4040921-1"])
        # lobid's version of a heading replaces the MARC-built one in place.
        self.assertEqual(entry["subjects"][2]["label"], "Qaraḍāwī, Yūsuf al-")
        self.assertEqual(entry["ddc"], ["297.09051", "297.09"])
        self.assertEqual(entry["isbn"], ["9783110726534"])
        self.assertEqual(entry["fp"], book.fp)

    def test_empty_fields_are_omitted(self) -> None:
        book = prepare_book(raw_book("e", "9783110726534"))
        entry = merge(book, [record("lobid", "https://lobid.org/resources/e", {"9783110726534"})])
        self.assertEqual(set(entry), {"isbn", "fp", "records"})


def fake_lookups(results: dict[str, list[CatalogueRecord]]):
    """Patch both fetchers to answer from ``results`` (query form → records)."""
    calls: list[str] = []

    def fetch(catalogue):
        def inner(client, forms):
            calls.append(forms[0])
            found = [r for form in forms for r in results.get(form, []) if r.catalogue == catalogue]
            return list(dict.fromkeys(found))
        return inner

    patches = mock.patch.multiple(fs, fetch_dnb=fetch("dnb"), fetch_lobid=fetch("lobid"))
    return patches, calls


class RunTests(unittest.TestCase):
    def setUp(self) -> None:
        self.books = [
            prepare_book(raw_book("islam", "3593397609", title="Muslim Worlds")),
            prepare_book(raw_book("nowhere", "9780367503901", title="Baba Padmanji")),
            prepare_book(raw_book("broken", "978110847879", title="Broken")),
        ]
        self.results = {
            "9783593397603": [
                record("dnb", "https://d-nb.info/9", {"9783593397603"}, title="Muslim Worlds",
                       subjects=[Heading("4027743-4", "Islam", "SubjectHeading")]),
                record("lobid", "https://lobid.org/resources/9", {"9783593397603"}, title="Muslim worlds",
                       subjects=[Heading("4000695-5", "Afrika", "PlaceOrGeographicName")]),
            ],
        }

    def run_enrich(self, books, cache=None):
        patches, calls = fake_lookups(self.results)
        with patches:
            payload, stats = enrich(books, client=None, cache=cache, log=lambda *_: None)
        return payload, stats, calls

    def test_payload_shape(self) -> None:
        payload, stats, calls = self.run_enrich(self.books)
        self.assertEqual(calls, ["9783593397603", "9783593397603", "9780367503901", "9780367503901"])
        self.assertEqual(payload["sources"], {"lobid": "https://lobid.org/resources",
                                              "dnb": "https://services.dnb.de/sru/dnb"})
        self.assertEqual(payload["coverage"], {
            "books": 3, "with_valid_isbn": 2, "matched": 1,
            "matched_by": {"lobid": 1, "dnb": 1}, "with_subjects": 1,
        })
        self.assertEqual(list(payload["books"]), ["islam"])
        self.assertEqual([s["label"] for s in payload["books"]["islam"]["subjects"]], ["Islam", "Afrika"])
